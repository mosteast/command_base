"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "../../test/fixture/yaml_patch");

function write(relative_path, content) {
  const absolute = path.join(ROOT, relative_path);
  fs.mkdirSync(path.dirname(absolute), { recursive: true });
  fs.writeFileSync(absolute, content);
  return absolute;
}

function write_scale_stream(relative_path, node_count, min_bytes) {
  const absolute = path.join(ROOT, relative_path);
  fs.mkdirSync(path.dirname(absolute), { recursive: true });
  const stream = fs.createWriteStream(absolute);
  stream.write("root:\n");
  let bytes = 6;
  let index = 0;
  while (index < node_count || bytes < min_bytes) {
    const line =
      index < node_count
        ? `  item_${index}: value_${index}\n`
        : `  pad_${index}: ${"x".repeat(128)}\n`;
    stream.write(line);
    bytes += Buffer.byteLength(line, "utf8");
    index += 1;
  }
  stream.end();
  return new Promise((resolve, reject) => {
    stream.on("finish", () => resolve({ path: absolute, bytes, nodes: index }));
    stream.on("error", reject);
  });
}

function generate_baseline() {
  write("baseline/01_plain.yaml", "name: value\nenabled: true\ncount: 3\n");
  write(
    "baseline/02_quoted.yaml",
    "plain: text\nsingle: 'quoted'\ndouble: \"quoted\"\n",
  );
  write(
    "baseline/03_block.yaml",
    "literal: |\n  line one\n  line two\nfolded: >\n  folded\n  text\n",
  );
  write(
    "baseline/04_flow.yaml",
    "map: { a: 1, b: 2 }\nseq: [one, two, three]\n",
  );
  write(
    "baseline/05_comments.yaml",
    "# header\nitem: value # inline\n\n# separator\nnext: 1\n",
  );
  write(
    "baseline/06_multi_document.yaml",
    "---\nfirst: 1\n---\nsecond: 2\n...\n",
  );
  write(
    "baseline/07_anchors.yaml",
    "defaults: &defaults\n  timeout: 30\nservice:\n  <<: *defaults\n  name: api\n",
  );
  write("baseline/08_custom_tags.yaml", "!custom tagged: value\nplain: keep\n");
  write(
    "baseline/09_unicode.yaml",
    "cjk: 中文\nja: 日本語\ncombo: Cafe\u0301\nemoji: 😀\n",
  );
  write("baseline/10_bom.yaml", "\uFEFFvalue: bom\n");
  write("baseline/11_crlf.yaml", "value: crlf\r\nnext: line\r\n");
  write("baseline/12_mixed_newlines.yaml", "a: 1\rb: 2\nc: 3\r\n");
  write("baseline/13_no_final_newline.yaml", "value: nonewline");
  write(
    "baseline/14_directives.yaml",
    "%YAML 1.2\n%TAG ! tag:example.com,2026:\n---\nvalue: ok\n",
  );
}

function generate_path_cases() {
  write("path/with space.yaml", "value: space\n");
  write("path/with[brackets].yaml", "value: brackets\n");
  write("path/with*star.yaml", "value: star\n");
  write("path/unicodé.yaml", "value: unicode-name\n");
}

async function main() {
  fs.rmSync(ROOT, { recursive: true, force: true });
  fs.mkdirSync(ROOT, { recursive: true });
  generate_baseline();
  generate_path_cases();
  const nodes_64k = await write_scale_stream("scale/nodes_64k.yaml", 64_000, 0);
  const large_2mib = await write_scale_stream(
    "scale/large_2mib.yaml",
    30_000,
    2 * 1024 * 1024,
  );
  const growth = await write_scale_stream(
    "scale/growth_10x.yaml",
    Math.max(nodes_64k.nodes * 10, large_2mib.nodes * 10),
    Math.max(nodes_64k.bytes * 10, large_2mib.bytes * 10),
  );
  write(
    "README.md",
    `# YAML Patch Fixtures

Generated by \`node benchmark/yaml_patch/generate_fixture.js\`.

- \`baseline/\`: 14 deterministic YAML shape cases
- \`path/\`: literal path characters for glob tests
- \`scale/\`: large synthetic corpora for resource/benchmark checks

Scale summary:
- nodes_64k: ${nodes_64k.nodes} entries, ${nodes_64k.bytes} bytes
- large_2mib: ${large_2mib.nodes} entries, ${large_2mib.bytes} bytes
- growth_10x: ${growth.nodes} entries, ${growth.bytes} bytes
`,
  );
  console.log(
    JSON.stringify(
      {
        root: ROOT,
        nodes_64k,
        large_2mib,
        growth_10x: growth,
      },
      null,
      2,
    ),
  );
}

if (require.main === module) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}

module.exports = { main, ROOT };
